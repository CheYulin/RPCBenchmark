import copy
import struct
import unittest

from analyze_closed import (analyze_rows, decode_pod_rows, expected_selected_keys,
                            merge_prefix_rows, nearest_rank_stats)


def fixture(operation='get'):
    plan = dict(callers=2, warm_per_caller=4, measure_per_caller=6,
                seed=17, modulus=2, operation=operation)
    slots = [dict(caller=i, cached_tid=100 + i) for i in range(2)]
    method = 1 if operation == 'get' else 4
    summary = {'phases': {1: dict(attempts=8, success=8, errors=0, histogram_count=8),
                          2: dict(attempts=12, success=12, errors=0, histogram_count=12)}}
    ledgers, ends, rpcs = [], [], []
    # Frozen external selector oracle, not generated by the module under test.
    for phase, ids in [(1, [1, 3, 4, 6, 7]), (2, [1, 3, 4, 6, 7, 11])]:
        for arrival in ids:
            caller = arrival % 2
            begin = phase * 10000 + arrival * 1000
            duration = 100 + arrival * 7
            ledgers.append(dict(phase_id=phase, arrival_id=arrival, caller_index=caller,
                                linux_tid=100 + caller, api_begin_ns=begin,
                                api_end_ns=begin + duration + 40,
                                validation_end_ns=begin + duration + 45,
                                status_code=0, scheduled_ns=begin))
            ends.append(dict(phase_id=phase, arrival_id=arrival, caller_index=caller,
                             api_begin_ns=begin, api_end_ns=begin + duration + 40,
                             validation_end_ns=begin + duration + 45,
                             scheduled_ns=begin, outcome=0, flags=1,
                             observed_methods=1 << method, capture_errors=0, rpc_count=1))
            rpcs.append(dict(phase_id=phase, arrival_id=arrival, caller_index=caller,
                             rpc_ordinal=1, method=method, send_ns=begin + 10,
                             recv_ns=begin + 10 + duration, server_processing_ns=20 + arrival * 3,
                             server_execution_ns=10 + arrival * 3,
                             controller_error=0, ds_error=0, flags=1 | 256 | 1024))
    return plan, ledgers, ends, rpcs, slots, summary


class AnalyzerTests(unittest.TestCase):
    def analyze(self, values=None):
        return analyze_rows(*(fixture() if values is None else values))

    def bad(self, mutate):
        values = fixture()
        mutate(values)
        result = self.analyze(values)
        self.assertFalse(result['diagnostic_valid'])
        self.assertTrue(result['validation_errors'])
        self.assertEqual(result['raw_rows']['ledgers'], values[1])
        self.assertEqual(result['raw_rows']['ends'], values[2])
        self.assertEqual(result['raw_rows']['rpcs'], values[3])
        self.assertFalse(result['RPC30_accepted'])

    def test_complete_get(self):
        result = self.analyze()
        self.assertTrue(result['diagnostic_valid'], result['validation_errors'])
        self.assertEqual(result['phases']['2']['selected_api_count'], 6)
        self.assertEqual(result['phases']['2']['rpc']['count'], 6)
        self.assertEqual(result['phases']['2']['server_processing']['count'], 6)
        self.assertFalse(result['RPC30_accepted'])

    def test_set_requires_publish(self):
        self.assertTrue(self.analyze(fixture('set'))['diagnostic_valid'])
        values = fixture('set')
        values[3][0]['method'] = 1
        self.assertFalse(self.analyze(values)['diagnostic_valid'])

    def test_missing_ledger(self): self.bad(lambda v: v[1].pop())
    def test_duplicate_ledger(self): self.bad(lambda v: v[1].append(copy.deepcopy(v[1][0])))
    def test_missing_end(self): self.bad(lambda v: v[2].pop())
    def test_duplicate_end(self): self.bad(lambda v: v[2].append(copy.deepcopy(v[2][0])))
    def test_out_of_plan_id(self): self.bad(lambda v: v[1][0].update(arrival_id=99))
    def test_wrong_caller(self): self.bad(lambda v: v[1][0].update(caller_index=0))
    def test_wrong_phase(self): self.bad(lambda v: v[1][0].update(phase_id=3))
    def test_wrong_tid(self): self.bad(lambda v: v[1][0].update(linux_tid=999))
    def test_shifted_timestamp(self): self.bad(lambda v: v[2][0].update(api_end_ns=v[2][0]['api_end_ns'] + 1))
    def test_reversed_validation(self): self.bad(lambda v: v[1][0].update(validation_end_ns=1))
    def test_unexpected_scheduled_time(self): self.bad(lambda v: v[1][0].update(scheduled_ns=1))
    def test_api_error(self): self.bad(lambda v: v[1][0].update(status_code=1))
    def test_global_count_mismatch(self): self.bad(lambda v: v[5]['phases'][2].update(attempts=11))
    def test_histogram_count_mismatch(self): self.bad(lambda v: v[5]['phases'][2].update(histogram_count=11))
    def test_global_api_error(self): self.bad(lambda v: v[5]['phases'][2].update(success=11, errors=1))
    def test_slot_error(self): self.bad(lambda v: v[4][0].update(errors=1))
    def test_missing_slot(self): self.bad(lambda v: v[4].pop())
    def test_unknown_method(self): self.bad(lambda v: v[3][0].update(method=99))
    def test_duplicate_rpc_ordinal(self): self.bad(lambda v: v[3].append(copy.deepcopy(v[3][0])))
    def test_rpc_ordinal_gap(self): self.bad(lambda v: v[3][0].update(rpc_ordinal=2))
    def test_rpc_endpoint_outside_api(self): self.bad(lambda v: v[3][0].update(send_ns=1))
    def test_rpc_failure(self): self.bad(lambda v: v[3][0].update(controller_error=1))
    def test_capture_end_error(self): self.bad(lambda v: v[2][0].update(capture_errors=1))
    def test_anomaly_unselected_rows_retained(self):
        def mutation(v):
            row = copy.deepcopy(v[3][0])
            row.update(arrival_id=0, flags=2)
            v[3].append(row)
        self.bad(mutation)

    def test_set_multi_rpc_primary_and_api_residual_denominators(self):
        values = fixture('set')
        end, publish = values[2][0], values[3][0]
        create = copy.deepcopy(publish)
        create.update(method=3, rpc_ordinal=1, send_ns=end['api_begin_ns'] + 1,
                      recv_ns=end['api_begin_ns'] + 5, flags=1,
                      server_processing_ns=0, server_execution_ns=0)
        publish['rpc_ordinal'] = 2
        end.update(rpc_count=2, observed_methods=(1 << 3) | (1 << 4))
        values[3].append(create)
        result = self.analyze(values)
        self.assertTrue(result['diagnostic_valid'], result['validation_errors'])
        phase = result['phases']['1']
        self.assertEqual(phase['rpc']['count'], 6)
        self.assertEqual(phase['primary_rpc']['count'], 5)
        self.assertEqual(phase['rpc_by_method']['3']['count'], 1)
        self.assertEqual(phase['single_rpc_api_minus_rpc']['count'], 4)

    def test_missing_optional_metadata_keeps_primary(self):
        values = fixture()
        for row in values[3]: row.update(flags=1, server_processing_ns=0, server_execution_ns=0)
        result = self.analyze(values)
        self.assertTrue(result['diagnostic_valid'])
        self.assertEqual(result['phases']['2']['rpc']['count'], 6)
        self.assertEqual(result['phases']['2']['metadata_states']['processing']['missing'], 6)
        self.assertEqual(result['phases']['2']['server_processing']['count'], 0)
        self.assertIsNone(result['phases']['2']['server_processing']['p99_ns'])

    def test_invalid_optional_metadata_keeps_primary(self):
        values = fixture()
        for row in values[3]: row.update(flags=1 | 512 | 2048 | 4096,
                                          server_processing_ns=999999, server_execution_ns=999998)
        result = self.analyze(values)
        self.assertTrue(result['diagnostic_valid'])
        self.assertEqual(result['phases']['2']['rpc']['count'], 6)
        self.assertEqual(result['phases']['2']['metadata_states']['processing']['invalid'], 6)
        self.assertEqual(result['phases']['2']['rpc_minus_server_processing']['count'], 0)

    def test_residual_computed_before_quantiles(self):
        values = fixture()
        rows = [r for r in values[3] if r['phase_id'] == 2]
        for i, row in enumerate(rows):
            duration, processing = [(100, 1), (110, 100)][i] if i < 2 else (100, 99)
            row.update(recv_ns=row['send_ns'] + duration, server_processing_ns=processing,
                       server_execution_ns=0, flags=1 | 256)
        result = self.analyze(values)
        self.assertTrue(result['diagnostic_valid'])
        phase = result['phases']['2']
        self.assertEqual(phase['rpc_minus_server_processing']['p99_ns'], 99)
        self.assertNotEqual(phase['rpc_minus_server_processing']['p99_ns'],
                            phase['rpc']['p99_ns'] - phase['server_processing']['p99_ns'])

    def test_bad_optional_span_does_not_become_zero(self):
        values = fixture()
        values[3][-1].update(server_processing_ns=100000)
        result = self.analyze(values)
        self.assertTrue(result['diagnostic_valid'])
        phase = result['phases']['2']
        self.assertEqual(phase['rpc']['count'], 6)
        self.assertEqual(phase['server_processing']['count'], 5)
        self.assertEqual(phase['metadata_states']['processing']['invalid'], 1)

    def test_observed_method_mask_must_match_rpc_rows(self):
        self.bad(lambda v: v[2][0].update(observed_methods=(1 << 1) | (1 << 4)))

    def test_boolean_status_not_numeric_zero(self):
        self.bad(lambda v: v[1][0].update(status_code=False))

    def test_zero_selection_plan_rejected(self):
        plan = fixture()[0]; plan['modulus'] = (1 << 32) - 1
        with self.assertRaises(ValueError): expected_selected_keys(plan)

    def test_unknown_flags_rejected(self):
        self.bad(lambda v: v[3][0].update(flags=v[3][0]['flags'] | 128))

    def test_input_not_mutated(self):
        values = fixture(); before = copy.deepcopy(values)
        self.analyze(values)
        self.assertEqual(values, before)

    def test_small_selector_oracle(self):
        keys = expected_selected_keys(fixture()[0])
        self.assertEqual(keys, {(p, i, i % 2) for p, ids in
                               [(1, [1, 3, 4, 6, 7]), (2, [1, 3, 4, 6, 7, 11])] for i in ids})

    def test_real_plan_selected_counts(self):
        plan = dict(callers=32, warm_per_caller=8192, measure_per_caller=49152,
                    seed=17, modulus=512, operation='get')
        keys = expected_selected_keys(plan)
        self.assertEqual(sum(p == 1 for p, _, _ in keys), 527)
        self.assertEqual(sum(p == 2 for p, _, _ in keys), 3065)

    def test_invalid_plan(self):
        for change in [dict(callers=0), dict(modulus=0), dict(seed=-1), dict(operation='exist')]:
            plan = fixture()[0]; plan.update(change)
            with self.assertRaises(ValueError): expected_selected_keys(plan)

    def test_nearest_rank_and_empty(self):
        self.assertEqual(nearest_rank_stats([100, 2, 3])['p50_ns'], 3)
        self.assertEqual(nearest_rank_stats([100, 2, 3])['p99_ns'], 100)
        self.assertIsNone(nearest_rank_stats([])['p99_ns'])

    def test_duplicate_warm_prefix_not_double_counted(self):
        rows = fixture()[2]
        warm = [r for r in rows if r['phase_id'] == 1]
        self.assertEqual(merge_prefix_rows(warm, rows, 'end'), rows)

    def test_conflicting_warm_prefix_rejected(self):
        rows = fixture()[2]; warm = copy.deepcopy([r for r in rows if r['phase_id'] == 1])
        warm[0]['api_end_ns'] += 1
        with self.assertRaises(ValueError): merge_prefix_rows(warm, rows, 'end')

    def test_duplicate_in_single_prefix_rejected(self):
        rows = fixture()[3]
        with self.assertRaises(ValueError): merge_prefix_rows([], rows + [rows[0]], 'rpc')

    def test_missing_warm_from_final_rejected(self):
        rows = fixture()[2]
        with self.assertRaises(ValueError): merge_prefix_rows(rows[:1], rows[1:], 'end')

    def test_pod_rpc_little_and_big_endian(self):
        values = (1, 10, 20, 3, 2, 2, 1, 1, 4, 0, 0, 1)
        for order, prefix in [('little', '<'), ('big', '>')]:
            blob = struct.pack(prefix + '5Q2I2H2iI', *values)
            self.assertEqual(len(blob), 64)
            row = decode_pod_rows(blob, 'rpc', order)[0]
            self.assertEqual((row['arrival_id'], row['method'], row['phase_id']), (1, 4, 2))

    def test_pod_end_and_truncated(self):
        blob = struct.pack('<8Q2IiI', 2, 1, 10, 10, 20, 21, 16, 0, 1, 1, 0, 1)
        self.assertEqual(len(blob), 80)
        self.assertEqual(decode_pod_rows(blob, 'end', 'little')[0]['rpc_count'], 1)
        with self.assertRaises(ValueError): decode_pod_rows(blob[:-1], 'end', 'little')
        with self.assertRaises(ValueError): decode_pod_rows(blob, 'end', 'native')


